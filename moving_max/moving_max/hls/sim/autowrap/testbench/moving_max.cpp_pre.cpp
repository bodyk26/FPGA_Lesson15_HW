void moving_max(int in_data[64], int out_data[64]) {
    int window[8];

INIT_LOOP:
    for (int k = 0; k < 8; k++) {


                   window[k] = (-2147483647 -1);
    }

MAIN_LOOP:

    for (int n = 0; n < 64; n++) {



        for(int k = 8 -1; k > 0; k--){
            window[k] = window[k-1] ;
        }


        window[0] = in_data[n];


        int max = window[0];

        for(int k = 1; k < 8; k++)
            if(window[k] > max) max = window[k];

        out_data[n] = max;
    }
}
